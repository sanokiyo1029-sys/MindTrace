def _m(mid, subject, label, friendly, title, steps):
    return {"id": mid, "topic": DEFAULT_TOPIC[subject], "subject": subject, "label": label,
            "student_friendly": friendly, "teaching_activity": {"title": title, "minutes": 5, "steps": steps}}


def _other(prefix, subject):
    return _m(f"M_{prefix}_OTHER", subject, "Another possible misunderstanding of this idea (teacher to check)",
              "This answer doesn't match the idea yet. Look at the explanation and try a similar question.",
              "Explain it back", ["Ask two students to explain their answer.", "Model the idea with one example.",
                                  "Give a similar question and compare reasoning."])


