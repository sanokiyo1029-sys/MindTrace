def _q(subject, concept, stem, options, answer, explanation, distractors, difficulty="easy"):
    return {"topic": DEFAULT_TOPIC[subject], "subject": subject, "type": "mcq", "concept": concept, "stem": stem,
            "options": options, "answer": answer, "explanation": explanation,
            "distractors": {k: {"misconception_id": m, "why": w} for k, (m, w) in distractors.items()},
            "difficulty": difficulty, "source": "sample"}


def _d(subject, concept, stem, model_answer, look_for, difficulty="medium"):
    return {"topic": DEFAULT_TOPIC[subject], "subject": subject, "type": "descriptive", "concept": concept,
            "stem": stem, "model_answer": model_answer, "look_for": look_for, "difficulty": difficulty,
            "source": "sample"}


